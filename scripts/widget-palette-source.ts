/**
 * Renders `src/theme/tokens.ts` as native color tables for the widgets (D26).
 *
 * Pure string-building, shared by two callers so they can never disagree:
 *
 * - `scripts/generate-widget-palette.ts` writes the files (run it after ANY tokens.ts change);
 * - `src/__tests__/widgetPalette.test.ts` regenerates the same strings and fails the suite when a
 *   checked-in file has drifted — the native side has no test runner, so the drift test is what
 *   keeps "color lives in the theme" true across languages.
 *
 * The palettes are emitted verbatim, every key, as ARGB ints. Which roles a widget actually uses
 * is the renderer's business; generating a subset would just mean regenerating on every new use.
 */

import {
  buddyDiscLight,
  buddyDiscNight,
  nightPaper,
  paperLight,
  type BuddyColorName,
  type Palette,
} from '../src/theme/tokens';

/** `#rrggbb`, `#rgb`, or `rgba(r,g,b,a)` → ARGB, as android.graphics.Color wants it. */
export function argb(value: string): number {
  const hex = /^#([0-9a-f]{6})$/i.exec(value.trim());
  if (hex !== null) return (0xff000000 | Number.parseInt(hex[1], 16)) >>> 0;
  const short = /^#([0-9a-f]{3})$/i.exec(value.trim());
  if (short !== null) {
    const [r, g, b] = short[1].split('').map((c) => Number.parseInt(c + c, 16));
    return ((0xff << 24) | (r << 16) | (g << 8) | b) >>> 0;
  }
  const rgba = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([0-9.]+)\s*\)$/i.exec(value.trim());
  if (rgba !== null) {
    const [r, g, b] = [Number(rgba[1]), Number(rgba[2]), Number(rgba[3])];
    const a = Math.round(Number(rgba[4]) * 255);
    return ((a << 24) | (r << 16) | (g << 8) | b) >>> 0;
  }
  throw new Error(`Unparseable color in tokens.ts: ${value}`);
}

/** `0xAARRGGBB` Kotlin literal. */
function kotlinColor(value: string): string {
  return `0x${argb(value).toString(16).padStart(8, '0')}.toInt()`;
}

function kotlinMap(palette: Palette): string {
  return Object.entries(palette)
    .map(([key, value]) => `      "${key}" to ${kotlinColor(value)},`)
    .join('\n');
}

function kotlinBuddyMap(discs: Record<BuddyColorName, string>): string {
  return Object.entries(discs)
    .map(([key, value]) => `      "${key}" to ${kotlinColor(value)},`)
    .join('\n');
}

function swiftBuddyMap(discs: Record<BuddyColorName, string>): string {
  return Object.entries(discs)
    .map(([key, value]) => `    "${key}": 0x${argb(value).toString(16).padStart(8, '0').toUpperCase()},`)
    .join('\n');
}

function swiftMap(palette: Palette): string {
  return Object.entries(palette)
    .map(([key, value]) => `    "${key}": 0x${argb(value).toString(16).padStart(8, '0').toUpperCase()},`)
    .join('\n');
}

/** The full text of `targets/widget/WidgetPalette.swift`. */
export function swiftPaletteSource(): string {
  return `import SwiftUI

// GENERATED by scripts/generate-widget-palette.ts from src/theme/tokens.ts — do not edit.
// The app forbids color literals outside src/theme; this file is that rule's native shadow,
// regenerated (never hand-tuned) and pinned by src/__tests__/widgetPalette.test.ts.

/// The Paper & Seal palettes as ARGB, keyed by their tokens.ts names.
enum WidgetPalette {
  static let light: [String: UInt32] = [
${swiftMap(paperLight)}
  ]

  static let night: [String: UInt32] = [
${swiftMap(nightPaper)}
  ]

  /// Buddy disc colors (D177). Their own tables because these are people, not the app's chrome.
  static let buddyLight: [String: UInt32] = [
${swiftBuddyMap(buddyDiscLight)}
  ]

  static let buddyNight: [String: UInt32] = [
${swiftBuddyMap(buddyDiscNight)}
  ]

  /// A role's color; an unknown role is a programmer error and renders loud magenta in debug.
  static func color(_ role: String, night: Bool) -> Color {
    let table = night ? WidgetPalette.night : light
    return Color(argb: table[role] ?? 0xFFFF00FF)
  }

  /// A buddy's disc color by name. An unknown name falls back to the accent rather than to magenta:
  /// it should look like a buddy, not like a bug, if a future color name ever reaches an old build.
  static func buddyColor(_ name: String, night: Bool) -> Color {
    let table = night ? buddyNight : buddyLight
    return Color(argb: table[name] ?? (night ? 0xFFBF9950 : 0xFF8A6420))
  }
}

extension Color {
  init(argb: UInt32) {
    self.init(
      .sRGB,
      red: Double((argb >> 16) & 0xFF) / 255,
      green: Double((argb >> 8) & 0xFF) / 255,
      blue: Double(argb & 0xFF) / 255,
      opacity: Double((argb >> 24) & 0xFF) / 255
    )
  }
}
`;
}

/** The full text of a `WidgetPalette.kt`, for the given package (widgets module or Wear app). */
export function kotlinPaletteSource(packageName = 'expo.modules.prayerwidgets'): string {
  return `package ${packageName}

// GENERATED by scripts/generate-widget-palette.ts from src/theme/tokens.ts — do not edit.
// The app forbids color literals outside src/theme; this file is that rule's native shadow,
// regenerated (never hand-tuned) and pinned by src/__tests__/widgetPalette.test.ts.

/** The Paper & Seal palettes as ARGB ints, keyed by their tokens.ts names. */
internal object WidgetPalette {
  val light: Map<String, Int> =
    mapOf(
${kotlinMap(paperLight)}
    )

  val night: Map<String, Int> =
    mapOf(
${kotlinMap(nightPaper)}
    )

  /** Buddy disc colors (D177). Their own maps because these are people, not the app's chrome. */
  val buddyLight: Map<String, Int> =
    mapOf(
${kotlinBuddyMap(buddyDiscLight)}
    )

  val buddyNight: Map<String, Int> =
    mapOf(
${kotlinBuddyMap(buddyDiscNight)}
    )

  /** A role's color, honest about programmer error: an unknown key throws in debug-shaped code paths. */
  fun color(role: String, night: Boolean): Int =
    (if (night) this.night else light)[role]
      ?: error("Unknown palette role: " + role)

  /**
   * A buddy's disc color by name. Unlike a role, an unknown name falls back to the accent instead of
   * throwing: a color added in a later app version reaching an older widget should look like a
   * buddy, not take the widget down.
   */
  fun buddyColor(name: String, night: Boolean): Int =
    (if (night) buddyNight else buddyLight)[name]
      ?: (if (night) 0xffbf9950.toInt() else 0xff8a6420.toInt())
}
`;
}
