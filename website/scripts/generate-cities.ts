/**
 * Turns `data/cities.tsv` into one lazily-loaded module per locale, in `src/lib/cities/`.
 *
 * WHY THE SITE CARRIES A CITY LIST AT ALL (D149). The app does not have one — D09 chose the OS
 * geocoder precisely so there would be no bundled database and no API key. A browser has no
 * geocoder, and `connect-src 'none'` forbids asking a service, so the only way `/times` can name a
 * place is to ship the places. The same list does three jobs, which is what makes it worth its
 * weight: it answers the city search, it turns a geolocated coordinate into a city name and a
 * country code (nearest-neighbour), and it carries the IANA zone the times are rendered in.
 *
 * WHY ONE FILE PER LOCALE. An Arabic reader searching for القاهرة should find it, so each chunk
 * carries the names in its own locale. Splitting means /ar never downloads the Turkish spellings.
 *
 * WHY IT IS LAZY. This is 30-ish KB gzipped and most visits never need it: someone who has already
 * chosen a location has it in `localStorage`, and the daily quick-check path must stay light. The
 * pages load it with a dynamic `import()`, which the CSP covers under `script-src 'self'` — a
 * `fetch()` would need `connect-src`, which stays `'none'`.
 *
 * Run automatically by `bun run build`.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const IN = join(HERE, '..', 'data', 'cities.tsv');
const OUT = join(HERE, '..', 'src', 'lib', 'cities');

const LOCALES = ['en', 'ar', 'tr', 'ur'] as const;
type Locale = (typeof LOCALES)[number];

interface Row {
  name: string;
  ascii: string;
  cc: string;
  lat: number;
  lon: number;
  tz: string;
  ar: string;
  tr: string;
  ur: string;
}

const rows: Row[] = [];
for (const line of readFileSync(IN, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, name, ascii, cc, lat, lon, tz, ar, tr, ur] = line.split('\t');
  rows.push({ name, ascii, cc, lat: Number(lat), lon: Number(lon), tz, ar: ar ?? '', tr: tr ?? '', ur: ur ?? '' });
}
if (rows.length === 0) throw new Error(`no cities parsed from ${IN}`);

/** Zones repeat heavily (2500 cities share ~400 zones), so intern them and store an index. */
const zones = [...new Set(rows.map((r) => r.tz))].sort();
const zoneIndex = new Map(zones.map((z, i) => [z, i]));

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

/**
 * The display name for a locale, and the Latin spelling to also match against.
 *
 * Someone reading the Arabic page may well type "Cairo" — plenty of people search for their own
 * city in Latin letters out of habit, or because that is what their keyboard is set to. So every
 * entry keeps its ASCII spelling as a second search key regardless of locale, and only the
 * *displayed* name changes.
 */
function displayName(r: Row, locale: Locale): string {
  if (locale === 'ar' && r.ar) return r.ar;
  if (locale === 'tr' && r.tr) return r.tr;
  // GeoNames' Urdu names occasionally use the Arabic ي ك ه; Urdu pages show the Urdu letters.
  if (locale === 'ur' && r.ur) return r.ur.replace(/ي/g, 'ی').replace(/ك/g, 'ک').replace(/ه/g, 'ہ');
  return r.name;
}

for (const locale of LOCALES) {
  const lines = rows.map((r) => {
    const display = displayName(r, locale);
    // The ASCII spelling is dropped when it adds nothing to match on.
    const alias = r.ascii && r.ascii !== display ? r.ascii : '';
    // Full four decimals, ~11 m. Two decimals looked defensible — a kilometre moves a prayer time
    // by seconds — but rounding to the displayed minute turns those seconds into a visible minute
    // often enough: Istanbul came out a minute adrift of the app. The bytes are not worth one
    // wrong-looking Fajr.
    return [display, alias, r.cc, r.lat.toFixed(4), r.lon.toFixed(4), zoneIndex.get(r.tz)!].join('\t');
  });

  const file = `// GENERATED by scripts/generate-cities.ts from ../../data/cities.tsv — do not edit.
// City data from GeoNames (CC BY 4.0) — credited on /support.
//
// One tab-delimited record per line: name, latinAlias, countryCode, lat, lon, zoneIndex.
// A packed string rather than a JSON array of arrays: same data, roughly a third fewer bytes over
// the wire, because it spends nothing on quotes and brackets and gives gzip a longer run to chew
// on. Parsing it is one split per line, done once, off the critical path.
//
// \`latinAlias\` is empty when it would repeat \`name\`; it exists so someone on the Arabic page can
// still type "Cairo" and find القاهرة.

export const zones: readonly string[] = ${JSON.stringify(zones)};

export const packed = ${JSON.stringify(lines.join('\n'))};
`;
  writeFileSync(join(OUT, `${locale}.ts`), file);
}

const sizes = LOCALES.map((l) => {
  const bytes = readFileSync(join(OUT, `${l}.ts`)).length;
  return `${l} ${Math.round(bytes / 1024)}KB`;
}).join(', ');

console.log(`cities generated — ${rows.length} cities, ${zones.length} zones (${sizes} uncompressed)`);
