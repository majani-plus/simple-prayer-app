/**
 * Copies the app's pure domain modules and its shared vocabulary into this project, as
 * `src/lib/domain/` and `src/lib/appStrings.generated.ts`.
 *
 * WHY A COPY AND NOT AN IMPORT: exactly the reason `generate-tokens.ts` gives at length. With the
 * Cloudflare Pages project root set to `website/`, only this directory's dependencies are installed,
 * but Vite still transforms a file imported from `../../src/` and looks for its nearest tsconfig —
 * the repo root's, which `extends: "expo/tsconfig.base"`. Expo is not installed there, so the build
 * dies with "Cannot find module 'expo/tsconfig.base/tsconfig.json'". The coupling therefore crosses
 * the boundary at BUILD time: this script runs under Bun (which executes TypeScript natively and
 * consults no tsconfig), and Vite only ever sees files inside `website/`.
 *
 * The output is regenerated on every build and is git-ignored, so it cannot go stale and there is no
 * second copy of the app's source in the history for someone to edit by mistake.
 *
 * The site must agree with the app to the minute. Two things would break that quietly, so both are
 * tripwires here rather than review habits:
 *   1. A React/React Native/Expo import appearing in a domain module — it would bundle and then fail
 *      in a browser, or drag the whole framework in.
 *   2. The import graph growing an edge to a module we do not copy.
 * Either fails this script, and therefore the build, with a message naming the file.
 *
 * Run automatically by `bun run build`.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const REPO = join(HERE, '..', '..');
const SRC = join(REPO, 'src', 'domain');
const OUT = join(HERE, '..', 'src', 'lib', 'domain');

/**
 * The closed set of modules the site needs. `prayerTimes` pulls in dates/methods/windows/types;
 * `hijri` and `prayerNames` render the date line; `qibla` is bearing and distance only.
 * Everything else in `src/domain/` is tracking logic the website deliberately does not have.
 */
const MODULES = [
  'types',
  'dates',
  'windows',
  'methods',
  'prayerTimes',
  'hijri',
  'prayerNames',
  'qibla',
] as const;

/** Imports that must never appear in code we are about to run in a browser. */
const FORBIDDEN = /from\s+'(react|react-native|expo[-/]|@react-native|zustand)/;

/** `import ... from './x'` / `export ... from './x'` — the relative edges of the graph. */
const RELATIVE_EDGE = /(?:import|export)[\s\S]*?from\s+'\.\/([a-zA-Z0-9_]+)'/g;

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const copied: string[] = [];
for (const name of MODULES) {
  const source = readFileSync(join(SRC, `${name}.ts`), 'utf8');

  const forbidden = source.match(FORBIDDEN);
  if (forbidden) {
    throw new Error(
      `src/domain/${name}.ts imports ${forbidden[1]} — the website bundles these modules for the ` +
        `browser, so domain code must stay free of React, React Native and Expo.`
    );
  }

  for (const [, edge] of source.matchAll(RELATIVE_EDGE)) {
    if (!(MODULES as readonly string[]).includes(edge)) {
      throw new Error(
        `src/domain/${name}.ts imports './${edge}', which the website does not copy. Add it to ` +
          `MODULES in this script if the site genuinely needs it, or keep the dependency out of ` +
          `the modules the site shares.`
      );
    }
  }

  const banner =
    `// GENERATED by scripts/generate-domain.ts from ../../src/domain/${name}.ts — do not edit.\n` +
    `// Regenerated on every \`bun run build\`; edit the app's copy instead.\n\n`;
  writeFileSync(join(OUT, `${name}.ts`), banner + source);
  copied.push(name);
}

/* ---------------------------------------------------------------------------------------------- *
 * Shared vocabulary.
 *
 * TONE.md requires the site to use the app's exact wording for anything the audience already knows
 * by name — the prayers, the Hijri months, the compass letters. Copying them mechanically is the
 * only way that survives a copy edit in either place.
 * ---------------------------------------------------------------------------------------------- */

const LOCALES = ['en', 'ar', 'tr', 'ur'] as const;

/**
 * Anything here is a sentence the app already says. The site must say it the same way — a reader
 * who has both should never meet two wordings for one idea — so these are lifted rather than
 * re-authored, in all three languages at once. Copy the site invents for itself (page titles, the
 * line about what the app does that this page does not) lives in `src/i18n/` and is authored there.
 */
interface AppStrings {
  prayers: Record<string, string>;
  prayersArabic: Record<string, string>;
  hijriMonths: Record<string, string>;
  hijriEra: string;
  hijriDayMonth: string;
  dateLine: string;
  cardinal: Record<string, string>;
  /** "upcoming", "next", "now · until {{time}}" — the row captions, verbatim from Today. */
  caption: Record<string, string>;
  sunrise: string;
  /** Durations, with the plural forms i18next stores as `hour_one` / `hour_other`. */
  time: Record<string, unknown>;
  location: Record<string, string>;
  /** "Diyanet", "ISNA", "Umm al-Qura" — the authority the page names beneath the times. */
  methods: Record<string, string>;
  /** The qibla vocabulary the site reuses: bearing/distance labels, the turn guidance, the
   *  no-compass sentence. The app has said all of this for a year; the site should not invent
   *  a second way to say it. */
  qibla: Record<string, unknown>;
}

/**
 * The qibla strings the site reuses. Left behind deliberately: `accuracy`, `calibration`,
 * `recalibrate` and `magneticNote` all describe controls and sensor detail the web has no
 * equivalent for, and `tilt` is replaced by a web-specific line, because holding the phone flat
 * matters here in a way it no longer does in the app (D142).
 */
const QIBLA_KEYS = [
  'cardinal', 'value', 'guide', 'status', 'card', 'makkah', 'noCompass', 'arabic', 'dial',
] as const;

/** The location strings the site reuses. The rest of that namespace is about app-only screens. */
const LOCATION_KEYS = [
  'useMyLocation', 'resolving', 'permissionDenied', 'approximate',
  'chooseCity', 'searchPlaceholder', 'searching', 'noResults', 'retry',
] as const;

const localeFile = (locale: string) => join(REPO, 'src', 'i18n', 'locales', `${locale}.json`);

/** `over` laid on `base`, key by key: what `over` lacks, `base` supplies. */
function merge(base: any, over: any): any {
  if (typeof base !== 'object' || base === null || typeof over !== 'object' || over === null) {
    return over ?? base;
  }
  const out: any = { ...base };
  for (const [k, v] of Object.entries(over)) out[k] = merge(base[k], v);
  return out;
}

/**
 * Urdu is newer than the other three and may be partial (or, before the app's file lands, absent).
 * Missing keys fall back to English so the site always builds, and the build says so out loud.
 */
function readLocale(locale: string): any {
  const own = existsSync(localeFile(locale)) ? JSON.parse(readFileSync(localeFile(locale), 'utf8')) : null;
  if (locale !== 'ur') {
    if (!own) throw new Error(`missing ${localeFile(locale)}`);
    return own;
  }
  if (!own) console.warn(`generate-domain: ${localeFile(locale)} not found — /ur uses English app strings`);
  return merge(JSON.parse(readFileSync(localeFile('en'), 'utf8')), own ?? {});
}

function stringsFor(locale: string): AppStrings {
  const raw = readLocale(locale);
  const { arabic, ...prayers } = raw.prayers;
  return {
    prayers,
    prayersArabic: arabic,
    hijriMonths: raw.hijri.months,
    hijriEra: raw.hijri.era.ah,
    hijriDayMonth: raw.hijri.dayMonth,
    dateLine: raw.today.dateLine,
    cardinal: raw.qibla.cardinal,
    caption: raw.today.caption,
    sunrise: raw.today.sunrise.label,
    time: raw.time,
    location: Object.fromEntries(LOCATION_KEYS.map((k) => [k, raw.location[k]])),
    methods: Object.fromEntries(
      Object.entries(raw.methods).filter(([, v]) => typeof v === 'string')
    ) as Record<string, string>,
    qibla: Object.fromEntries(
      QIBLA_KEYS.filter((k) => k in raw.qibla).map((k) => [k, raw.qibla[k]])
    ),
  };
}

const strings = Object.fromEntries(LOCALES.map((l) => [l, stringsFor(l)]));

const stringsFile = `// GENERATED by scripts/generate-domain.ts from ../../src/i18n/locales/*.json — do not edit.
// The words the app and the site must say identically: prayer names, Hijri months, compass letters.
// Site-authored copy lives in src/i18n/ and is NOT generated — see TONE.md on authoring ar/tr.

export interface AppStrings {
  prayers: Record<string, string>;
  prayersArabic: Record<string, string>;
  hijriMonths: Record<string, string>;
  hijriEra: string;
  hijriDayMonth: string;
  dateLine: string;
  cardinal: Record<string, string>;
  qibla: Record<string, any>;
  caption: Record<string, string>;
  sunrise: string;
  time: {
    countdown: string;
    now: string;
    durationPair: string;
    unit: Record<string, string>;
  };
  location: Record<string, string>;
  methods: Record<string, string>;
}

export const appStrings: Record<'en' | 'ar' | 'tr' | 'ur', AppStrings> = ${JSON.stringify(strings, null, 2)};
`;

writeFileSync(join(HERE, '..', 'src', 'lib', 'appStrings.generated.ts'), stringsFile);

/* ---------------------------------------------------------------------------------------------- *
 * The adhan patch.
 *
 * D121/D122: adhan 4.4.4 has two real defects we repair in the package itself — `roundedMinute`
 * pushing an exact minute a full minute late, and an impossible polar Asr. The site computes the
 * same times with the same library, so it needs the same patch; an unpatched site would disagree
 * with the app by a minute and nobody would notice until someone compared two screens.
 *
 * `bun install` needs the patch before this script ever runs, so `website/patches/` is committed.
 * This check exists to catch the copy drifting from the root one.
 * ---------------------------------------------------------------------------------------------- */

const PATCH = 'adhan@4.4.6.patch';
const rootPatch = readFileSync(join(REPO, 'patches', PATCH), 'utf8');
const sitePatchPath = join(HERE, '..', 'patches', PATCH);

let sitePatch = '';
try {
  sitePatch = readFileSync(sitePatchPath, 'utf8');
} catch {
  mkdirSync(join(HERE, '..', 'patches'), { recursive: true });
  copyFileSync(join(REPO, 'patches', PATCH), sitePatchPath);
  sitePatch = rootPatch;
  console.log(`patches/${PATCH} created from the root copy — commit it.`);
}

if (sitePatch !== rootPatch) {
  throw new Error(
    `website/patches/${PATCH} differs from patches/${PATCH}. The site must run the same patched ` +
      `adhan as the app (D121/D122), or the two will disagree by a minute. Copy the root patch over.`
  );
}

console.log(
  `domain vendored — ${copied.length} modules (${copied.join(', ')}), ` +
    `strings for ${LOCALES.join('/')}, adhan patch verified`
);
