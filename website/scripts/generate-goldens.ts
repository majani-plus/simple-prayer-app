/**
 * Freezes the app's prayer times into `data/prayer-goldens.json`, the baseline the website is
 * checked against.
 *
 * WHY THIS EXISTS. The check used to compare the vendored copy against the app's own modules, live,
 * in the same process. That works on a developer's machine and **failed on Cloudflare**, for a
 * reason worth writing down: `patchedDependencies` is a bun feature, Cloudflare auto-detects the
 * repo-root `package.json` and installs it with **npm**, and npm does not apply bun's patches. So
 * the root `node_modules/adhan` was unpatched, the website's own was patched, and the comparison
 * dutifully reported 99 disagreements between the correct answer and the wrong one — including
 * rows like "app 08:07 vs site 08:07", which differ only in the sub-second residue the patch
 * clears (D121/D122).
 *
 * A baseline that depends on how somebody else's install ran is not a baseline. So the values are
 * frozen here, once, and committed. This mirrors what the app already does for itself: D120 keeps
 * `src/domain/prayerTimes.golden.test.ts` as the tripwire that makes a floating dependency safe.
 *
 * REGENERATING. Run `bun run goldens` from `website/`, with the repo root installed by **bun** so
 * the adhan patch is applied — this script refuses to run otherwise. A diff in the output is not a
 * nuisance to be committed away: it means the times moved. Verify the new values against the
 * authority's published timetable for that city before accepting them, exactly as D120 requires.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { computeDayTimes } from '../../src/domain/prayerTimes';
import { qiblaBearing, distanceToKaabaKm } from '../../src/domain/qibla';
import { CASES, DAYS, key, MADHABS, MARKERS, settingsFor } from './goldens-matrix';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const REPO = join(HERE, '..', '..');
const OUT = join(HERE, '..', 'data', 'prayer-goldens.json');

/** The patch's own comment, as it appears in the installed package. */
const PATCH_MARKER = 'already on an exact minute is its own ceiling';

const installed = join(REPO, 'node_modules', 'adhan', 'lib', 'esm', 'DateUtils.js');
if (!readFileSync(installed, 'utf8').includes(PATCH_MARKER)) {
  throw new Error(
    `The repo-root adhan is NOT patched, so these goldens would freeze the wrong answers.\n` +
      `patches/adhan@4.4.6.patch is applied by \`bun install\` and ignored by npm — run\n` +
      `\`bun install\` at the repo root and try again.`
  );
}

const times: Record<string, number[]> = {};
const qibla: Record<string, [number, number]> = {};

for (const madhab of MADHABS) {
  for (const c of CASES) {
    for (const day of DAYS) {
      try {
        const computed = computeDayTimes(day, c.location, settingsFor(madhab));
        times[key(c.city, day, madhab)] = MARKERS.map((m) => computed.times[m].getTime());
      } catch {
        // A refusal is part of the contract: the domain throws rather than answer wrongly, and the
        // website must refuse in the same places. An empty array records "this one must throw".
        times[key(c.city, day, madhab)] = [];
      }
    }
  }
}

// The qibla is pure geometry and does not depend on the madhab or the day.
for (const c of CASES) {
  qibla[c.city] = [qiblaBearing(c.location), distanceToKaabaKm(c.location)];
}

const payload = {
  _note:
    'GENERATED by scripts/generate-goldens.ts from the app under a bun install (patched adhan). ' +
    'Do not hand-edit. A diff here means the computed times moved — verify against the authority ' +
    'before accepting it (docs/DECISIONS.md D120).',
  _markers: MARKERS,
  _generated: new Date().toISOString().slice(0, 10),
  times,
  qibla,
};

writeFileSync(OUT, JSON.stringify(payload, null, 1) + '\n');
console.log(
  `goldens written — ${Object.keys(times).length} day/city/madhab rows, ${Object.keys(qibla).length} qibla points`
);
