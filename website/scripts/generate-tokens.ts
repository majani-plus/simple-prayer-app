/**
 * Copies the app's design tokens into this project as `src/styles/tokens.generated.ts`.
 *
 * The site must never drift from the palette the app ships (docs/DECISIONS.md D50), and the
 * obvious way to guarantee that is to import `../../src/theme/tokens.ts` directly. That works on a
 * developer's machine and FAILS on Cloudflare Pages: with the project root set to `website/`, only
 * this directory's dependencies are installed, but Vite still transforms the imported file and
 * looks for its nearest tsconfig — the repo root's, which `extends: "expo/tsconfig.base"`. Expo is
 * not installed there, so the build dies with "Cannot find module 'expo/tsconfig.base/tsconfig.json'".
 * Overriding esbuild's tsconfig does not help, because Vite resolves the `extends` chain itself.
 *
 * So the coupling stays, but it crosses the boundary at BUILD time instead of at bundle time:
 * this script runs under Bun (which executes TypeScript natively and consults no tsconfig), reads
 * the single source of truth, and writes a plain module that lives inside the site. Vite then only
 * ever sees files in `website/`. The output is regenerated on every build, so it cannot go stale.
 *
 * Run automatically by `bun run build`.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { nightPaper, paperLight } from '../../src/theme/tokens';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const OUT = join(HERE, '..', 'src', 'styles', 'tokens.generated.ts');

/** Serialises a palette as a typed object literal, keys in their original order. */
function literal(name: string, palette: Record<string, string>): string {
  const body = Object.entries(palette)
    .map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`)
    .join('\n');
  return `export const ${name}: Palette = {\n${body}\n};`;
}

const keys = Object.keys(paperLight);
const missing = keys.filter((key) => !(key in nightPaper));
if (missing.length > 0) {
  // The app's own token test pins this too; failing here keeps a broken palette out of the site.
  throw new Error(`night palette is missing tokens: ${missing.join(', ')}`);
}

const file = `// GENERATED by scripts/generate-tokens.ts from ../../src/theme/tokens.ts — do not edit.
// Regenerated on every \`bun run build\`; see that script for why the site cannot import the
// app's module directly.

/** Every colour role the Paper & Seal language defines. */
export interface Palette {
${keys.map((key) => `  ${key}: string;`).join('\n')}
}

${literal('paperLight', paperLight as unknown as Record<string, string>)}

${literal('nightPaper', nightPaper as unknown as Record<string, string>)}
`;

writeFileSync(OUT, file);
console.log(`tokens.generated.ts written — ${keys.length} tokens x 2 palettes`);
